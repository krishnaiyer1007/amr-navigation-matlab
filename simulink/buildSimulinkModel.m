function mdl = buildSimulinkModel(cfg, mdlPath)
%BUILDSIMULINKMODEL Programmatically build simulink/amrNavigation.slx.
%   mdl = buildSimulinkModel()            build with defaultConfig()
%   mdl = buildSimulinkModel(cfg, path)   custom configuration / location
%
%   Subsystems (README section 11), fixed-step discrete, dt = cfg.dt:
%     Scenario & World           ground-truth obstacle motion        (bridge)
%     Range Sensor               simulated LiDAR from true pose      (bridge)
%     State Estimator            pose estimate (true pose pass-through)
%     Local Mapping & Tracking   clustering, tracks, local map       (bridge)
%     Global Planner             blockage check + A* replanning      (bridge)
%     Local Planner              look-ahead tracking + DWA           (bridge)
%     Safety Supervisor          speed/accel limits, inverse kinematics (native)
%     Wheel Controller           PI + feedforward, anti-windup         (native)
%     Differential Drive Plant   1st-order motors + kinematics + pose  (native)
%     Logger & Visualizer        truth checks, logging, stop           (bridge + To Workspace)
%   Physical constants are inlined from cfg at build time: rebuild after
%   changing robot / controller parameters.
    if nargin < 1 || isempty(cfg), cfg = defaultConfig(); end
    here = fileparts(mfilename('fullpath'));
    if nargin < 2, mdlPath = fullfile(here, 'amrNavigation.slx'); end
    [~, mdl] = fileparts(mdlPath);
    if bdIsLoaded(mdl), close_system(mdl, 0); end
    if exist(mdlPath, 'file'), delete(mdlPath); end
    new_system(mdl);
    set_param(mdl, 'Solver', 'FixedStepDiscrete', 'FixedStep', num2str(cfg.dt, 17), ...
        'StopTime', num2str(cfg.duration - cfg.dt, 17), 'SaveOutput', 'off', 'SaveTime', 'off', ...
        'ReturnWorkspaceOutputs', 'on', 'SignalLogging', 'off');
    % Run button support: InitFcn prepares the scenario, StopFcn collects
    % the result (see amrModelInit / amrModelStop for the base variables)
    set_param(mdl, 'InitFcn', 'amrModelInit', 'StopFcn', 'amrModelStop');
    % record the constants inlined below, so InitFcn can refuse a mismatch
    mws = get_param(mdl, 'ModelWorkspace');
    assignin(mws, 'amrBuiltConstants', struct('robot', cfg.robot, 'wheelPID', cfg.wheelPID, 'dt', cfg.dt));
    nb = cfg.sensor.numBeams;
    R = cfg.robot; G = cfg.wheelPID;
    f = @(x) sprintf('%.17g', x);

    % ---------------- block code ----------------
    code.world = sprintf(['function dyn = fcn(t)\n%%#codegen\n', ...
        '%% Scenario & World: advance scripted obstacles and hidden blockers (ground truth)\n', ...
        'coder.extrinsic(''amrSimBridge'');\ndyn = zeros(1, 18);\ndyn = amrSimBridge(''world'', t);\nend\n']);
    code.sensor = sprintf(['function ranges = fcn(poseTrue, dyn)\n%%#codegen\n', ...
        '%% Range Sensor: ray-cast LiDAR from the TRUE pose (-1 = no return)\n', ...
        'coder.extrinsic(''amrSimBridge'');\nranges = zeros(1, %d);\n', ...
        'ranges = amrSimBridge(''sense'', reshape(poseTrue, 1, 3));\nend\n'], nb);
    code.estimator = sprintf(['function poseEst = fcn(poseTrue, wheel)\n%%#codegen\n', ...
        '%% State Estimator: exact pose (cfg.odom.useTruePose = true baseline).\n', ...
        '%% Replace with odometry / localisation to study estimation error.\n', ...
        'poseEst = reshape(poseTrue, 1, 3);\nend\n']);
    code.mapping = sprintf(['function nTracks = fcn(ranges, poseEst, t)\n%%#codegen\n', ...
        '%% Local Mapping & Tracking: clustering, alpha-beta tracks, observed-obstacle grid\n', ...
        'coder.extrinsic(''amrSimBridge'');\nnTracks = zeros(1, 2);\n', ...
        'nTracks = amrSimBridge(''perceive'', reshape(poseEst, 1, 3), t);\nend\n']);
    code.planner = sprintf(['function status = fcn(nTracks, t)\n%%#codegen\n', ...
        '%% Global Planner: blockage detection, debounced A* replanning\n', ...
        '%% status = [nWaypoints blocked replans]\n', ...
        'coder.extrinsic(''amrSimBridge'');\nstatus = zeros(1, 3);\n', ...
        'status = amrSimBridge(''replan'', t);\nend\n']);
    code.local = sprintf(['function req = fcn(poseEst, prevCmd, status)\n%%#codegen\n', ...
        '%% Local Planner: look-ahead tracking + DWA-style velocity sampling\n', ...
        '%% req = [vRequest wRequest mode]  (mode 0 normal, 1 evasive, 2 stop)\n', ...
        'coder.extrinsic(''amrSimBridge'');\nreq = zeros(1, 3);\n', ...
        'req = amrSimBridge(''command'', reshape(poseEst, 1, 3), reshape(prevCmd, 1, 2));\nend\n']);
    code.supervisor = sprintf(['function [cmd, wheelTarget] = fcn(req, prevCmd)\n%%#codegen\n', ...
        '%% Safety Supervisor: speed and acceleration limits (limitCommand), then\n', ...
        '%% inverse kinematics to wheel speed targets.\n', ...
        'dt = %s; vMin = %s; vMax = %s; wMax = %s; aMax = %s; alphaMax = %s;\n', ...
        'r = %s; b = %s;\n', ...
        'v = min(max(req(1), vMin), vMax);\nw = min(max(req(2), -wMax), wMax);\n', ...
        'v = min(max(v, prevCmd(1) - aMax * dt), prevCmd(1) + aMax * dt);\n', ...
        'w = min(max(w, prevCmd(2) - alphaMax * dt), prevCmd(2) + alphaMax * dt);\n', ...
        'cmd = [v w];\n', ...
        'wheelTarget = [(cmd(1) + cmd(2) * b / 2) / r, (cmd(1) - cmd(2) * b / 2) / r];\nend\n'], ...
        f(cfg.dt), f(R.vMin), f(R.vMax), f(R.wMax), f(R.aMax), f(R.alphaMax), f(R.wheelRadius), f(R.wheelBase));
    code.wheel = sprintf(['function u = fcn(target, actual)\n%%#codegen\n', ...
        '%% Wheel Controller: PI(D) with feedforward and conditional-integration anti-windup\n', ...
        'persistent integ prevErr\nif isempty(integ), integ = [0 0]; prevErr = [0 0]; end\n', ...
        'dt = %s; Kp = %s; Ki = %s; Kd = %s; iMax = %s; uMax = %s;\n', ...
        'target = reshape(target, 1, 2); actual = reshape(actual, 1, 2);\n', ...
        'e = target - actual;\nintegCand = integ + e * dt;\n', ...
        'integCand = min(max(integCand, -iMax / max(Ki, eps)), iMax / max(Ki, eps));\n', ...
        'd = (e - prevErr) / dt;\nuCand = target + Kp * e + Ki * integCand + Kd * d;\n', ...
        'sat = abs(uCand) > uMax;\nnewInteg = integCand;\n', ...
        'for i = 1:2\n    if sat(i), newInteg(i) = integ(i); end\nend\n', ...
        'u = target + Kp * e + Ki * newInteg + Kd * d;\nu = min(max(u, -uMax), uMax);\n', ...
        'integ = newInteg; prevErr = e;\nend\n'], ...
        f(cfg.dt), f(G.Kp), f(G.Ki), f(G.Kd), f(G.iMax), f(R.wheelSpeedMax));
    if R.idealWheels
        motorLine = 'wheel = reshape(target, 1, 2);';
    else
        motorLine = sprintf(['a = 1 - exp(-dt / tau);\nwheel = wheelPrev + a * (u - wheelPrev);\n', ...
            'wheel = min(max(wheel, -%s), %s);'], f(R.wheelSpeedMax), f(R.wheelSpeedMax));
    end
    if strcmp(R.integrator, 'midpoint')
        integ = ['thm = p(3) + 0.5 * w * dt;\n', ...
                 'pose = [p(1) + v * cos(thm) * dt, p(2) + v * sin(thm) * dt, p(3) + w * dt];\n'];
    else
        integ = 'pose = [p(1) + v * cos(p(3)) * dt, p(2) + v * sin(p(3)) * dt, p(3) + w * dt];\n';
    end
    code.plant = sprintf(['function [wheel, vw, pose] = fcn(u, target, wheelPrev, posePrev)\n%%#codegen\n', ...
        '%% Differential Drive Plant: first-order wheel motors (exact ZOH),\n', ...
        '%% v = r/2 (wR + wL), w = r/b (wR - wL), pose integration, yaw wrap.\n', ...
        'dt = %s; tau = %s; r = %s; b = %s;\n', ...
        'u = reshape(u, 1, 2); target = reshape(target, 1, 2); wheelPrev = reshape(wheelPrev, 1, 2);\n', ...
        '%s\n', ...
        'v = r / 2 * (wheel(1) + wheel(2));\nw = r / b * (wheel(1) - wheel(2));\n', ...
        'p = reshape(posePrev, 1, 3);\n', integ, ...
        'pose(3) = mod(pose(3) + pi, 2*pi) - pi;\nvw = [v w];\nend\n'], ...
        f(cfg.dt), f(R.motorTau), f(R.wheelRadius), f(R.wheelBase), motorLine);
    code.logger = sprintf(['function done = fcn(pose, vw, wheel, cmd, t)\n%%#codegen\n', ...
        '%% Logger: ground-truth collision / goal / failure checks and run log\n', ...
        'coder.extrinsic(''amrSimBridge'');\ndone = 0;\n', ...
        'done = amrSimBridge(''post'', reshape(pose, 1, 3), reshape(vw, 1, 2), reshape(wheel, 1, 2), reshape(cmd, 1, 2), t);\nend\n']);

    % ---------------- layout ----------------
    W = 230; H = 90;
    blocks = { ...
      'Scenario & World',          'world',      [40   60],  {'t'},                                   {'dyn'}; ...
      'Range Sensor',              'sensor',     [340  60],  {'poseTrue','dyn'},                      {'ranges'}; ...
      'State Estimator',           'estimator',  [340 230],  {'poseTrue','wheel'},                    {'poseEst'}; ...
      'Local Mapping & Tracking',  'mapping',    [640  60],  {'ranges','poseEst','t'},                {'nTracks'}; ...
      'Global Planner',            'planner',    [940  60],  {'nTracks','t'},                         {'status'}; ...
      'Local Planner',             'local',      [940 230],  {'poseEst','prevCmd','status'},          {'req'}; ...
      'Safety Supervisor',         'supervisor', [1240 230], {'req','prevCmd'},                       {'cmd','wheelTarget'}; ...
      'Wheel Controller',          'wheel',      [1240 400], {'target','actual'},                     {'u'}; ...
      'Differential Drive Plant',  'plant',      [940  400], {'u','target','wheelPrev','posePrev'},   {'wheel','vw','pose'}; ...
      'Logger & Visualizer',       'logger',     [640  400], {'pose','vw','wheel','cmd','t'},         {'done'}};
    rt = sfroot;
    for i = 1:size(blocks, 1)
        name = blocks{i,1}; pos = blocks{i,3};
        sub = [mdl '/' name];
        add_block('simulink/Ports & Subsystems/Subsystem', sub, 'Position', [pos pos + [W H]]);
        % clear default content
        delete_line(sub, 'In1/1', 'Out1/1'); delete_block([sub '/In1']); delete_block([sub '/Out1']);
        fbName = [regexprep(name, '[^A-Za-z0-9]', '') 'Fcn'];
        fb = [sub '/' fbName];
        add_block('simulink/User-Defined Functions/MATLAB Function', fb, 'Position', [200 40 420 40 + 40 * max(numel(blocks{i,4}), numel(blocks{i,5}))]);
        ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', fb);
        ch.Script = code.(blocks{i,2});
        ins = blocks{i,4}; outs = blocks{i,5};
        for j = 1:numel(ins)
            add_block('simulink/Sources/In1', [sub '/' ins{j}], 'Position', [40 40+40*j 70 54+40*j], 'Port', num2str(j));
            add_line(sub, [ins{j} '/1'], sprintf('%s/%d', fbName, j));
        end
        for j = 1:numel(outs)
            add_block('simulink/Sinks/Out1', [sub '/' outs{j}], 'Position', [520 40+40*j 550 54+40*j], 'Port', num2str(j));
            add_line(sub, sprintf('%s/%d', fbName, j), [outs{j} '/1']);
        end
        set_param(sub, 'BackgroundColor', colorFor(blocks{i,2}));
    end

    % ---------------- sources, states, sinks ----------------
    add_block('simulink/Sources/Digital Clock', [mdl '/Clock'], 'SampleTime', num2str(cfg.dt, 17), 'Position', [-120 85 -80 115]);
    add_block('simulink/Discrete/Unit Delay', [mdl '/Pose State'], 'InitialCondition', 'amrStartPose', ...
        'SampleTime', num2str(cfg.dt, 17), 'Position', [1300 560 1350 600]);
    add_block('simulink/Discrete/Unit Delay', [mdl '/Wheel State'], 'InitialCondition', '[0 0]', ...
        'SampleTime', num2str(cfg.dt, 17), 'Position', [1300 640 1350 680]);
    add_block('simulink/Discrete/Unit Delay', [mdl '/Command State'], 'InitialCondition', '[0 0]', ...
        'SampleTime', num2str(cfg.dt, 17), 'Position', [1560 300 1610 340]);
    add_block('simulink/Sinks/Stop Simulation', [mdl '/Stop'], 'Position', [960 560 990 590]);
    add_block('simulink/Logic and Bit Operations/Compare To Constant', [mdl '/Done?'], ...
        'relop', '>', 'const', '0.5', 'Position', [900 560 940 590]);
    sinks = {'pose', 'slPose'; 'vw', 'slVel'; 'cmd', 'slCmd'; 'ranges', 'slRanges'; 'dyn', 'slDyn'; 'status', 'slPlanStatus'; 'req', 'slRequest'};
    for i = 1:size(sinks, 1)
        add_block('simulink/Sinks/To Workspace', [mdl '/Log ' sinks{i,1}], 'VariableName', sinks{i,2}, ...
            'SaveFormat', 'Array', 'Position', [1700 40+70*i 1790 70+70*i]);
    end

    % ---------------- wiring ----------------
    L = @(a, b) add_line(mdl, a, b, 'autorouting', 'smart');
    L('Clock/1', 'Scenario & World/1');
    L('Scenario & World/1', 'Range Sensor/2');
    L('Pose State/1', 'Range Sensor/1');
    L('Pose State/1', 'State Estimator/1');
    L('Wheel State/1', 'State Estimator/2');
    L('Range Sensor/1', 'Local Mapping & Tracking/1');
    L('State Estimator/1', 'Local Mapping & Tracking/2');
    L('Clock/1', 'Local Mapping & Tracking/3');
    L('Local Mapping & Tracking/1', 'Global Planner/1');
    L('Clock/1', 'Global Planner/2');
    L('State Estimator/1', 'Local Planner/1');
    L('Command State/1', 'Local Planner/2');
    L('Global Planner/1', 'Local Planner/3');
    L('Local Planner/1', 'Safety Supervisor/1');
    L('Command State/1', 'Safety Supervisor/2');
    L('Safety Supervisor/1', 'Command State/1');
    L('Safety Supervisor/2', 'Wheel Controller/1');
    L('Wheel State/1', 'Wheel Controller/2');
    L('Wheel Controller/1', 'Differential Drive Plant/1');
    L('Safety Supervisor/2', 'Differential Drive Plant/2');
    L('Wheel State/1', 'Differential Drive Plant/3');
    L('Pose State/1', 'Differential Drive Plant/4');
    L('Differential Drive Plant/1', 'Wheel State/1');
    L('Differential Drive Plant/3', 'Pose State/1');
    L('Differential Drive Plant/3', 'Logger & Visualizer/1');
    L('Differential Drive Plant/2', 'Logger & Visualizer/2');
    L('Differential Drive Plant/1', 'Logger & Visualizer/3');
    L('Safety Supervisor/1', 'Logger & Visualizer/4');
    L('Clock/1', 'Logger & Visualizer/5');
    L('Logger & Visualizer/1', 'Done?/1');
    L('Done?/1', 'Stop/1');
    L('Differential Drive Plant/3', 'Log pose/1');
    L('Differential Drive Plant/2', 'Log vw/1');
    L('Safety Supervisor/1', 'Log cmd/1');
    L('Range Sensor/1', 'Log ranges/1');
    L('Scenario & World/1', 'Log dyn/1');
    L('Global Planner/1', 'Log status/1');
    L('Local Planner/1', 'Log req/1');

    % name key signals
    nameSignal(mdl, 'Differential Drive Plant', 3, 'pose');
    nameSignal(mdl, 'Range Sensor', 1, 'scan');
    nameSignal(mdl, 'Global Planner', 1, 'path status');
    nameSignal(mdl, 'Local Planner', 1, 'velocity request');
    nameSignal(mdl, 'Safety Supervisor', 1, 'command [v w]');
    nameSignal(mdl, 'Wheel Controller', 1, 'motor input');
    nameSignal(mdl, 'Local Mapping & Tracking', 1, 'tracks');

    add_block('built-in/Note', [mdl '/AMR navigation. Press Run to simulate scenario amrScenario (default S05) with controller amrController (default P). Navigation blocks call amrSimBridge (shared MATLAB code); plant, wheel PI and supervisor are native.'], ...
        'Position', [40 -40]);
    save_system(mdl, mdlPath);
    fprintf('Built %s\n', mdlPath);
end

function c = colorFor(kind)
    switch kind
        case {'world', 'sensor'}, c = 'lightBlue';
        case {'plant', 'wheel'}, c = 'orange';
        case {'supervisor'}, c = 'red';
        case {'logger'}, c = 'gray';
        otherwise, c = 'green';
    end
end

function nameSignal(mdl, blk, port, name)
    ph = get_param([mdl '/' blk], 'PortHandles');
    set_param(ph.Outport(port), 'Name', name);
end
